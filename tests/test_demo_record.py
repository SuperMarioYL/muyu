"""Recorded demo: byte-stable, and it measures the draft it claims to measure.

`docs/demo-results.json` is copied verbatim into web/site.json's demo steps and
regenerated by .github/workflows/demo.yml, which fails the job if the file
changed. So the record must (a) be reproducible byte for byte, and (b) actually
measure the raw draft — the annotated gallery files also contain the native
rewrite, and scoring those reports the corrected text's score instead.
"""

import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from muyu.scorer import score_text

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / "docs" / "demo-results.json"
BEFORE_MARKER = "## Before (score: see `muyu score`)"


def _record() -> dict:
    return json.loads(RECORD.read_text())


def test_recorded_demo_is_byte_stable(tmp_path):
    out = tmp_path / "demo-results.json"
    subprocess.run(
        [sys.executable, str(ROOT / "docs" / "record_demo_results.py"), "--out", str(out)],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    assert out.read_bytes() == RECORD.read_bytes(), (
        "regenerating the recorded demo changed it — the drift gate in "
        ".github/workflows/demo.yml requires the record to be reproducible"
    )


def test_demo_measures_the_draft_not_the_gallery_file():
    commands = [step["command"] for step in _record()["steps"]]
    assert any("examples/draft-1.md" in c for c in commands), commands
    assert any("examples/native-1.md" in c for c in commands), commands
    assert not any("before-after-" in c for c in commands), (
        "the demo must not score the annotated gallery file — it embeds the native "
        f"rewrite and the notes, so the reported score is not the draft's: {commands}"
    )


def test_recorded_pairs_are_the_scores_the_demo_reports():
    record = _record()
    for pair in record["example_pairs"]:
        draft = ROOT / "examples" / pair["example"]
        native = draft.with_name(draft.name.replace("draft-", "native-", 1))
        before, after = score_text(draft.read_text()), score_text(native.read_text())
        assert before.score == pair["before_score"], pair
        assert len(before.hits) == pair["before_tells"], pair
        assert after.score == pair["after_score"], pair
        assert len(after.hits) == pair["after_tells"], pair
        assert after.score - before.score == pair["delta"], pair


def test_gallery_blocks_stay_equal_to_the_draft_files():
    for draft in sorted((ROOT / "examples").glob("draft-*.md")):
        gallery = (ROOT / "examples" / draft.name.replace("draft-", "before-after-", 1)).read_text()
        before = gallery.split(BEFORE_MARKER)[1].split("## After")[0].strip()
        after = gallery.split("## After")[1].split("## Notes")[0].strip()
        assert draft.read_text() == before + "\n", f"{draft.name} drifted from its gallery page"
        native = ROOT / "examples" / draft.name.replace("draft-", "native-", 1)
        assert native.read_text() == after + "\n", f"{native.name} drifted from its gallery page"


def test_every_demo_command_list_agrees():
    """The demo command list lives in four places; keep them from drifting apart."""
    commands = [step["command"] for step in _record()["steps"]]
    owners = {
        "docs/demo.tape": (ROOT / "docs" / "demo.tape").read_text(),
        "docs/record_demo.py": (ROOT / "docs" / "record_demo.py").read_text(),
        "docs/render_demo_panels.py": (ROOT / "docs" / "render_demo_panels.py").read_text(),
    }
    for name, text in owners.items():
        for command in commands:
            assert command in text, f"{name} is missing the demo command: {command}"
